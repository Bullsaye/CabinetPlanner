/**
 * Assembles the pack folders in `packs/` (D76).
 *
 *   pnpm packs            writes packs/index.ts: static JSON imports of every
 *                         pack, so the engine, the app bundle and the tests
 *                         read the packs without file access
 *
 * A pack folder holds `pack.json` (metadata) and its content: one JSON array
 * per library kind (`materials.json`, `presets.json`, …) and/or a folder per
 * kind with one JSON file per item (`hardware/<id>.json`). `readPack` reads
 * one folder into the single-file form `{ ...pack.json, content }`: the form
 * the engine parses (`PackSchema`) and a server publishes.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Library kinds a pack may carry, in the order of the fragment (engine: LIBRARY_KINDS order of the schema). */
export const KINDS = ["materials", "edgebands", "hardware", "surfaces", "presets", "drawingStyles", "dxfProfiles", "templates"] as const;

const json = (file: string): unknown => JSON.parse(readFileSync(file, "utf8"));
const itemFiles = (dir: string): string[] =>
  existsSync(dir) && statSync(dir).isDirectory()
    ? readdirSync(dir)
        .filter((f) => f.endsWith(".json"))
        .sort()
    : [];

/** Pack folders below `root`: `core` first, the others by name. */
export function packDirs(root: string): string[] {
  const dirs = readdirSync(root)
    .filter((d) => existsSync(join(root, d, "pack.json")))
    .sort();
  return [...dirs.filter((d) => d === "core"), ...dirs.filter((d) => d !== "core")];
}

/** One pack folder as a single pack document. */
export function readPack(dir: string): Record<string, unknown> {
  const content: Record<string, unknown[]> = {};
  for (const kind of KINDS) {
    const items: unknown[] = [];
    if (existsSync(join(dir, `${kind}.json`))) items.push(...(json(join(dir, `${kind}.json`)) as unknown[]));
    for (const f of itemFiles(join(dir, kind))) items.push(json(join(dir, kind, f)));
    if (items.length) content[kind] = items;
  }
  return { ...(json(join(dir, "pack.json")) as object), content };
}

const ident = (s: string): string => s.replace(/\.json$/, "").replace(/[^A-Za-z0-9]+/g, "_");

/** Source of `packs/index.ts`. */
export function generateIndex(root: string): string {
  const imports: string[] = [];
  const packs: string[] = [];
  for (const d of packDirs(root)) {
    const p = ident(d);
    const use = (path: string, name: string): string => {
      imports.push(`import ${name} from "./${path}" with { type: "json" };`);
      return name;
    };
    const meta = use(`${d}/pack.json`, `${p}__pack`);
    const kinds: string[] = [];
    for (const kind of KINDS) {
      const parts: string[] = [];
      if (existsSync(join(root, d, `${kind}.json`))) parts.push(`...${use(`${d}/${kind}.json`, `${p}__${kind}`)}`);
      for (const f of itemFiles(join(root, d, kind))) parts.push(use(`${d}/${kind}/${f}`, `${p}__${kind}__${ident(f)}`));
      if (parts.length) kinds.push(`      ${kind}: [${parts.join(", ")}],`);
    }
    packs.push(`  {\n    ...${meta},\n    content: {\n${kinds.join("\n")}\n    },\n  },`);
  }
  return [
    "// Generated by `pnpm packs` (tools/packs/gen.ts) from the pack folders. Do not edit.",
    ...imports,
    "",
    "/** The bundled packs as single documents `{ ...pack.json, content }`, unvalidated; the engine parses them. */",
    "export const PACK_FILES: readonly unknown[] = [",
    ...packs,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const root = join(import.meta.dirname, "../../packs");
  writeFileSync(join(root, "index.ts"), generateIndex(root));
  console.log(`packs/index.ts: ${packDirs(root).length} packs`);
}
